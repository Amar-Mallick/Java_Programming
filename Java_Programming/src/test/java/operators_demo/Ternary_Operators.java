package operators_demo;

public class Ternary_Operators {

	public static void main(String[] args) {
		/* Ternary Operators  syntax ->>var=(Expression)?result1:result2;
		 * If, condition true result1 should be the output,else result2 will be output*/
		//Find which one is big number..............
		int a=100,b=50;
		int c=(a>b)?a:b;
		System.out.println("Big Number is :" + c);//Big Number is :100

	}

}
